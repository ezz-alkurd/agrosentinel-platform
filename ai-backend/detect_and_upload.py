import os
import uuid
import urllib.parse
import threading
from datetime import datetime, UTC

import cv2

from firebase_config import initialize_firebase
from firebase_diagnostics import FirebaseOperationError

# Initialize lazily so imports and local checks do not require cloud access.
db = bucket = None
_client_lock = threading.Lock()

def _clients():
    global db, bucket
    with _client_lock:
        if db is None or bucket is None:
            db, bucket = initialize_firebase()
    return db, bucket

def _device_doc(device_id):
    database, _ = _clients()
    return database.collection("devices").document(device_id)


def update_device_status(device_id, name, device_type, source, gps_lat, gps_lng,
                         models, online=True, started_at=None):
    """Write/refresh a device's presence heartbeat for the app.
    Reports to devices/<device_id> so several detectors can run at once."""
    public_source = str(source)
    if "://" in public_source:
        parts = urllib.parse.urlsplit(public_source)
        public_source = f"{parts.scheme}://{parts.hostname or 'camera'}"
    data = {
        "online": online,
        "name": name,                 # display name shown in the app
        "type": device_type,          # e.g. "Laptop camera"
        "source": public_source,
        "models": models,             # e.g. ["fire", "disease"]
        "gps_lat": float(gps_lat),
        "gps_lng": float(gps_lng),
        "last_seen": datetime.now(UTC).isoformat(),
    }
    if started_at:
        data["started_at"] = started_at
    _device_doc(device_id).set(data, merge=True)


def set_device_offline(device_id):
    """Best-effort mark a device offline (called on exit)."""
    try:
        _device_doc(device_id).set(
            {"online": False, "last_seen": datetime.now(UTC).isoformat()},
            merge=True,
        )
    except Exception:
        pass


def ensure_dir(path: str) -> None:
    os.makedirs(path, exist_ok=True)


def save_crop(image, bbox, output_dir="detections_local"):
    """
    Save cropped region from image using bbox = (x1, y1, x2, y2).
    """
    ensure_dir(output_dir)

    if image is None:
        raise ValueError("Input image is None.")

    height, width = image.shape[:2]
    x1, y1, x2, y2 = map(int, bbox)

    # Clamp bbox to image boundaries
    x1 = max(0, min(x1, width - 1))
    y1 = max(0, min(y1, height - 1))
    x2 = max(0, min(x2, width))
    y2 = max(0, min(y2, height))

    if x2 <= x1 or y2 <= y1:
        raise ValueError("Invalid bounding box: crop area is empty.")

    crop = image[y1:y2, x1:x2]

    filename = f"{uuid.uuid4().hex}.jpg"
    local_path = os.path.join(output_dir, filename)

    success = cv2.imwrite(local_path, crop)
    if not success:
        raise IOError("Failed to save cropped image.")

    return local_path, filename


def save_full_image(image, output_dir="detections_local"):
    """
    Save full image locally.
    """
    ensure_dir(output_dir)

    if image is None:
        raise ValueError("Input image is None.")

    filename = f"{uuid.uuid4().hex}.jpg"
    local_path = os.path.join(output_dir, filename)

    success = cv2.imwrite(local_path, image)
    if not success:
        raise IOError("Failed to save image.")

    return local_path, filename


def upload_image(local_path, anomaly_type):
    """
    Upload local file to Firebase Storage.
    Returns (storage_path, image_url) where image_url is a real Firebase
    download URL generated by embedding a random download token in the
    blob's metadata.  This URL works without requiring the caller to be
    authenticated and is compatible with Firebase Storage security rules.
    """
    if not os.path.exists(local_path):
        raise FileNotFoundError(f"Local file does not exist: {local_path}")

    today = datetime.now(UTC).strftime("%Y-%m-%d")
    filename = os.path.basename(local_path)

    storage_path = f"detections/{anomaly_type}/{today}/{filename}"

    _, storage_bucket = _clients()
    blob = storage_bucket.blob(storage_path)
    try:
        blob.upload_from_filename(local_path, timeout=15, retry=None)
    except Exception as error:
        raise FirebaseOperationError("Storage evidence upload", error) from error

    # Attach a random download token so Firebase generates a stable,
    # shareable download URL (same mechanism used by the Firebase Console).
    download_token = str(uuid.uuid4())
    blob.metadata = {"firebaseStorageDownloadTokens": download_token}
    try:
        blob.patch(timeout=15, retry=None)
    except Exception as error:
        raise FirebaseOperationError("Storage download-link metadata", error) from error

    # Build the Firebase Storage download URL
    encoded_path = urllib.parse.quote(storage_path, safe="")
    bucket_name = storage_bucket.name  # e.g. "agriculture-drone-e0dc0.firebasestorage.app"
    image_url = (
        f"https://firebasestorage.googleapis.com/v0/b/{bucket_name}"
        f"/o/{encoded_path}?alt=media&token={download_token}"
    )

    return storage_path, image_url


def log_event(anomaly_type, confidence, gps_lat, gps_lng, image_url, storage_path, extra=None):
    """
    Write detection event to Firestore.
    """
    data = {
        "anomaly_type": anomaly_type,
        "confidence": float(confidence),
        "gps_lat": float(gps_lat),
        "gps_lng": float(gps_lng),
        "timestamp": datetime.now(UTC).isoformat(),
        "image_url": image_url,
        "storage_path": storage_path,
        "status": "new",
    }

    if extra:
        data.update(extra)

    database, _ = _clients()
    try:
        doc_ref = database.collection("events").add(data, timeout=10, retry=None)
    except Exception as error:
        raise FirebaseOperationError("Firestore event write", error) from error
    return doc_ref


def handle_disease_classification(frame, disease_name, confidence, gps_lat, gps_lng, bbox=None, event_context=None):
    """
    Handle plant disease result.
    If bbox is provided, upload cropped detection.
    Otherwise upload full frame.
    """
    try:
        if bbox is not None:
            local_path, filename = save_crop(frame, bbox)
            saved_mode = "crop"
        else:
            local_path, filename = save_full_image(frame)
            saved_mode = "full_image"

        storage_path, image_url = upload_image(local_path, "disease")

        extra = {
            "source_file": filename,
            "disease_name": disease_name,
            "saved_mode": saved_mode,
        }

        if event_context:
            extra.update(event_context)
        if bbox is not None:
            extra["bbox"] = [int(v) for v in bbox]

        log_event(
            anomaly_type="disease",
            confidence=confidence,
            gps_lat=gps_lat,
            gps_lng=gps_lng,
            image_url=image_url,
            storage_path=storage_path,
            extra=extra,
        )

        print(f"[ok] Disease uploaded successfully: {disease_name}")
        print(f"Storage path: {storage_path}")
        print("Evidence image saved; review it in the app.")

    except Exception:
        print("[error] Event upload failed; no successful delivery is claimed.")
        raise


def handle_fire_detection(frame, label, confidence, gps_lat, gps_lng, bbox=None, event_context=None):
    """
    Handle fire / smoke detection result.

    Parameters
    ----------
    frame       : numpy ndarray — the full camera frame (BGR, from OpenCV)
    label       : str — raw YOLO class name, e.g. "fire" or "smoke"
    confidence  : float — YOLO confidence score (0.0 – 1.0)
    gps_lat     : float — GPS latitude (pass 0.0 if unavailable)
    gps_lng     : float — GPS longitude (pass 0.0 if unavailable)
    bbox        : tuple | list | None — (x1, y1, x2, y2) in pixels.
                  When supplied the bounding-box crop is uploaded;
                  otherwise the full frame is uploaded.

    Behaviour mirrors handle_disease_classification():
      1. Save crop (or full image) locally under detections_local/.
      2. Upload to Firebase Storage under detections/<label>/<date>/<uuid>.jpg.
      3. Write an event document to the Firestore `events` collection.
         - anomaly_type = label (so "smoke" is stored as "smoke", not "fire")
         - label field = raw class name

    INTEGRATION_RULES reference
    ---------------------------
    Rule §4  : anomaly_type for fire model = the actual detected label ("fire" or "smoke").
    Rule §7  : Classes containing "other" are excluded before this function is called.
    Rule §2  : Call this function only after the 2-second confirmation timer fires.
    Rule §3  : Call inside a non-daemon background thread so the upload isn't killed on exit.
    """
    try:
        if bbox is not None:
            local_path, filename = save_crop(frame, bbox)
            saved_mode = "crop"
        else:
            local_path, filename = save_full_image(frame)
            saved_mode = "full_image"

        # anomaly_type = the actual label ("fire" or "smoke") — see INTEGRATION_RULES §4
        anomaly_type = label.lower()
        storage_path, image_url = upload_image(local_path, anomaly_type)

        extra = {
            "source_file": filename,
            "label": label,
            "saved_mode": saved_mode,
        }

        if event_context:
            extra.update(event_context)
        if bbox is not None:
            extra["bbox"] = [int(v) for v in bbox]

        log_event(
            anomaly_type=anomaly_type,
            confidence=confidence,
            gps_lat=gps_lat,
            gps_lng=gps_lng,
            image_url=image_url,
            storage_path=storage_path,
            extra=extra,
        )

        print(f"[ok] Fire/smoke uploaded successfully: {label} ({confidence:.2%})")
        print(f"Storage path: {storage_path}")
        print("Evidence image saved; review it in the app.")

    except Exception:
        print("[error] Fire/smoke upload failed.")
        raise